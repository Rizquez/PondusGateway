package main

import (
	"context"
	"fmt"
	"io"
	"time"

	"pondus-gateway/internal/admission"
	"pondus-gateway/internal/core"
	"pondus-gateway/internal/execution"
	"pondus-gateway/internal/observability"
)

// outcome represents the result of an asynchronous execution.
type outcome struct {
	results []execution.Result
	err     error
}

// measureRun executes a batch of operations and collects metrics on execution
// and capacity utilization.
//
// It starts the Runner in a separate goroutine while periodically monitoring
// the reserved capacity via the admission controller.
//
// Records samples approximately every millisecond to calculate the observed
// maximum capacity and the estimated average utilization percentage relative
// to the total capacity provided.
//
// Upon completion of execution, it obtains a final sample, calculates the total
// duration and generates a report with the results of the operations and the capacity
// metrics.
//
// Returns the individual results, the metrics report and any error generated by
// Runner.Run, if any.
//
// Utilization metrics are estimates based on periodic samples and may not reflect
// capacity changes that occurred between observations.
func measureRun(
	ctx context.Context,
	runner *execution.Runner,
	controller *admission.Controller,
	operations []core.Operation,
	capacity uint64,
) ([]execution.Result, observability.Report, error) {
	finished := make(chan outcome, 1)

	start := time.Now()
	last := start

	var sampler observability.Sampler

	ticker := time.NewTicker(time.Millisecond)
	defer ticker.Stop()

	go func() {
		results, err := runner.Run(ctx, operations)
		finished <- outcome{
			results: results,
			err:     err,
		}
	}()

	for {
		select {
		case now := <-ticker.C:
			_, _, used := controller.Snapshot()

			sampler.Observe(used, now.Sub(last))
			last = now

		case result := <-finished:
			end := time.Now()

			_, _, used := controller.Snapshot()
			sampler.Observe(used, end.Sub(last))

			report := observability.Summarize(result.results, end.Sub(start))
			report.PeakUsed = sampler.PeakUsed()
			report.AverageUtilization = sampler.AverageUtilization(capacity)

			return result.results, report, result.err
		}
	}
}

// printReport writes a report containing the metrics obtained during
// the execution of a simulation.
//
// It displays the total number of operations and their results, including
// those that were completed, failed, canceled, and rejected.
//
// It also shows the total duration, the maximum reserved capacity observed
// and the estimated average
// capacity utilization percentage.
//
// The values are obtained directly from the provided report.
//
// The utilization percentage is displayed to two decimal places.
func printReport(output io.Writer, report observability.Report) {
	fmt.Fprintln(output, "\n--- Simulation metrics ---")
	fmt.Fprintf(output, "Total: %d\n", report.Total)
	fmt.Fprintf(output, "Completed: %d\n", report.Completed)
	fmt.Fprintf(output, "Failed: %d\n", report.Failed)
	fmt.Fprintf(output, "Cancelled: %d\n", report.Cancelled)
	fmt.Fprintf(output, "Rejected: %d\n", report.Rejected)

	fmt.Fprintf(
		output,
		"Duration: %s\n",
		report.Duration,
	)

	fmt.Fprintf(
		output,
		"Peak reserved capacity (observed): %d\n",
		report.PeakUsed,
	)

	fmt.Fprintf(
		output,
		"Average reserved utilization (estimated): %.2f%%\n",
		report.AverageUtilization,
	)
}
